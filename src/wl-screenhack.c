struct triangle_state {
    GLuint program;
    GLuint vbo;
    GLint  u_angle_loc;
    GLint  u_time_loc;
};

/*
 * Equilateral triangle in clip space, centered at origin, circumradius r=0.8.
 * Vertices at angles 90°, 210°, 330° from +Y — top, lower-left, lower-right.
 * Each vertex is a 2-component (x, y) vec2 to match `attribute vec2 a_pos`.
 *
 *   top       ( 0.0,             0.8)              = ( r·cos 90°,  r·sin 90°)
 *   lower-L   (-0.6928,         -0.4)              = ( r·cos210°,  r·sin210°)
 *   lower-R   ( 0.6928,         -0.4)              = ( r·cos330°,  r·sin330°)
 *
 * With r = 0.8: r·√3/2 ≈ 0.6928, and r/2 = 0.4.
 */
static const GLfloat k_triangle_verts[6] = {
     0.0f,    0.8f,
    -0.6928f, -0.4f,
     0.6928f, -0.4f,
};

/* Native GLES glDrawArrays — resolved via dlsym(RTLD_NEXT) once at init
 * time. gles3_compat's local glDrawArrays wrapper (when this binary is
 * linked against gles3_compat, or when this binary's draw is run from
 * inside a harness that has the wrapper installed) handles only the GL1
 * client-array case and silently no-ops a VBO-bound draw because the
 * scratch VAO has its own attribute layout. Calling the real libGLESv2
 * symbol directly is the only way to actually drive the GPU. Same
 * pattern as gles3_compat.c::ncz_gles3_runtime_init. */
typedef void (*triangle_real_glDrawArrays_fn)(GLenum, GLint, GLsizei);
static triangle_real_glDrawArrays_fn g_triangle_real_glDrawArrays = NULL;
static void triangle_draw_call(GLenum mode, GLint first, GLsizei count) {
    if (!g_triangle_real_glDrawArrays) {
        /* One-shot dlsym — RTLD_NEXT walks past this binary's own symbol
         * table to the next-loaded libGLESv2. If this binary isn't linked
         * against gles3_compat at all, dlsym returns the system libGLESv2
         * symbol directly. Either way the result is the real GPU entry. */
        g_triangle_real_glDrawArrays = (triangle_real_glDrawArrays_fn)
            dlsym(RTLD_NEXT, "glDrawArrays");
        if (!g_triangle_real_glDrawArrays) {
            fprintf(stderr,
                    "wl-screenhack: dlsym(RTLD_NEXT, glDrawArrays) failed: %s\n",
                    dlerror());
            exit(1);
        }
    }
    g_triangle_real_glDrawArrays(mode, first, count);
}

static const char *k_vertex_shader_src =
    "attribute vec2 a_pos;\n"
    "uniform float u_angle;\n"
    "void main() {\n"
    "    float c = cos(u_angle);\n"
    "    float s = sin(u_angle);\n"
    "    mat2 R = mat2(c, -s, s, c);\n"
    "    gl_Position = vec4(R * a_pos, 0.0, 1.0);\n"
    "}\n";

/*
 * Convert HSV (h in [0,1]) to RGB. Hue cycles through full rainbow at
 * 1 cycle / 12 s, so the triangle's color smoothly flows.
 */
static const char *k_fragment_shader_src =
    "precision mediump float;\n"
    "uniform float u_time;\n"
    "\n"
    "vec3 hsv2rgb(vec3 c) {\n"
    "    vec4 K = vec4(1.0, 2.0/3.0, 1.0/3.0, 3.0);\n"
    "    vec3 p = abs(fract(c.xxx + K.xyz) * 6.0 - K.www);\n"
    "    return c.z * mix(K.xxx, clamp(p - K.xxx, 0.0, 1.0), c.y);\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    float h = fract(u_time / 12.0);\n"
    "    vec3 rgb = hsv2rgb(vec3(h, 0.85, 1.0));\n"
    "    gl_FragColor = vec4(rgb, 1.0);\n"
    "}\n";

static GLuint compile_shader(GLenum type, const char *src, const char *label) {
    GLuint s = glCreateShader(type);
    if (s == 0) {
        GLenum err = glGetError();
        fprintf(stderr,
                "wl-screenhack: glCreateShader(%s, type=0x%x) returned 0 "
                "(glGetError=0x%x)\n",
                label, (unsigned int)type, (unsigned int)err);
        exit(1);
    }
    glShaderSource(s, 1, &src, NULL);
    glCompileShader(s);
    GLint ok = GL_FALSE;
    glGetShaderiv(s, GL_COMPILE_STATUS, &ok);
    if (!ok) {
        char log[512];
        GLsizei n = 0;
        glGetShaderInfoLog(s, sizeof(log), &n, log);
        fprintf(stderr,
                "wl-screenhack: %s shader compile failed (%" PRIu32 " bytes): %.*s\n",
                label, (uint32_t)n, (int)n, log);
        glDeleteShader(s);
        exit(1);
    }
    return s;
}

static int triangle_init(struct effect *e) {
    struct triangle_state *st = e->user;

    GLuint vs = compile_shader(GL_VERTEX_SHADER,   k_vertex_shader_src,   "vertex");
    GLuint fs = compile_shader(GL_FRAGMENT_SHADER, k_fragment_shader_src, "fragment");

    st->program = glCreateProgram();
    if (st->program == 0) {
        GLenum err = glGetError();
        fprintf(stderr,
                "wl-screenhack: glCreateProgram returned 0 (glGetError=0x%x)\n",
                (unsigned int)err);
        glDeleteShader(vs);
        glDeleteShader(fs);
        exit(1);
    }
    glAttachShader(st->program, vs);
    glAttachShader(st->program, fs);
    glBindAttribLocation(st->program, 0, "a_pos");
    glLinkProgram(st->program);

    /* Shaders may be deleted after link; they're retained by the program. */
    glDeleteShader(vs);
    glDeleteShader(fs);

    GLint ok = GL_FALSE;
    glGetProgramiv(st->program, GL_LINK_STATUS, &ok);
    if (!ok) {
        char log[512];
        GLsizei n = 0;
        glGetProgramInfoLog(st->program, sizeof(log), &n, log);
        fprintf(stderr,
                "wl-screenhack: program link failed (%" PRIu32 " bytes): %.*s\n",
                (uint32_t)n, (int)n, log);
        exit(1);
    }

    st->u_angle_loc = glGetUniformLocation(st->program, "u_angle");
    st->u_time_loc  = glGetUniformLocation(st->program, "u_time");

    glGenBuffers(1, &st->vbo);
    if (st->vbo == 0) {
        GLenum err = glGetError();
        fprintf(stderr,
                "wl-screenhack: glGenBuffers produced buffer name 0 "
                "(glGetError=0x%x)\n",
                (unsigned int)err);
        exit(1);
    }
    glBindBuffer(GL_ARRAY_BUFFER, st->vbo);
    glBufferData(GL_ARRAY_BUFFER, sizeof(k_triangle_verts),
                 k_triangle_verts, GL_STATIC_DRAW);
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    return 0;
}

static void triangle_reshape(struct effect *e, int width, int height) {
    /* Viewport is set in the per-frame draw, not here, so that a future
     * multi-pass effect can override it. Width/height are propagated so
     * a future effect can do aspect-correct ortho projection here. */
    (void)e;
    (void)width;
    (void)height;
}

static void triangle_draw(struct effect *e, double now_seconds) {
    struct triangle_state *st = e->user;

    /* Background: deep gray. The composit's overlay layer composites this
     * over whatever's underneath; we still clear so the framebuffer state
     * is well-defined. */
    glClearColor(0.06f, 0.06f, 0.08f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT);

    /* Wrap-safe rotation: fmod() guarantees the result is in [0, 2π) and
     * is well-behaved over arbitrarily long uptimes. Period: 12 s. */
    const float two_pi = 6.28318530717958647692f;
    float angle = (float)fmod(now_seconds * (two_pi / 12.0), two_pi);
    if (angle < 0.0f) angle += two_pi;

    glUseProgram(st->program);
    glUniform1f(st->u_angle_loc, angle);
    glUniform1f(st->u_time_loc,  (float)now_seconds);

    glBindBuffer(GL_ARRAY_BUFFER, st->vbo);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE,
                          (GLsizei)(2 * sizeof(GLfloat)), (void *)0);
    /* The compat layer's glDrawArrays shim (gles3_compat.c) handles only
     * GL1 client-array draws — it silently no-ops VBO-bound draws because
     * the immediate-mode scratch VAO is the only VAO whose attribute
     * layout matches the shim's expectations. Resolve libGLESv2's real
     * glDrawArrays via dlsym(RTLD_NEXT) so this VBO triangle actually
     * reaches the GPU. Same pattern as gles3_compat.c::ncz_gles3_runtime_init
     * (see commit 7b1cd0a which applied the matching fix to gles3_hyprsaver.c). */
    triangle_draw_call(GL_TRIANGLES, 0, 3);
    glDisableVertexAttribArray(0);
    glBindBuffer(GL_ARRAY_BUFFER, 0);
}

static void triangle_free(struct effect *e) {
    struct triangle_state *st = e->user;
    if (!st) return;
    if (st->vbo)     glDeleteBuffers(1, &st->vbo);
    if (st->program) glDeleteProgram(st->program);
    st->vbo = 0;
    st->program = 0;
}

