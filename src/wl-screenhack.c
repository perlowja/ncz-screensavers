/*
 * Choose an EGL config matching: ES2-capable, RGBA8, double-buffered,
 * with both window AND pbuffer surface types (the latter required by
 * EGL_KHR_surfaceless_context on some drivers; harmless to include).
 */
/*
 * Choose an EGL config: ES2-capable, RGBA8888, double-buffered window
 * surface. We don't request depth/stencil buffers — the test effect
 * uses 2D shapes only. Future rounds (port xscreensaver hacks) may
 * need to add EGL_DEPTH_SIZE=16 here.
 */
static EGLConfig choose_egl_config(EGLDisplay dpy) {
    EGLint cfg_attr[] = {
        EGL_SURFACE_TYPE,        EGL_WINDOW_BIT,
        EGL_RENDERABLE_TYPE,     EGL_OPENGL_ES2_BIT,
        EGL_RED_SIZE,            8,
        EGL_GREEN_SIZE,          8,
        EGL_BLUE_SIZE,           8,
        EGL_ALPHA_SIZE,          8,
        EGL_DEPTH_SIZE,          0,
        EGL_STENCIL_SIZE,        0,
        EGL_NONE,
    };
    EGLint num = 0;
    DIE(eglChooseConfig(dpy, cfg_attr, NULL, 0, &num), EGL_TRUE,
        "eglChooseConfig (probe) failed");
    if (num < 1) {
        fprintf(stderr,
                "wl-screenhack: no EGL configs match requested attributes\n");
        exit(1);
    }
    EGLConfig cfg;
    DIE(eglChooseConfig(dpy, cfg_attr, &cfg, 1, &num), EGL_TRUE,
        "eglChooseConfig failed");
    if (num < 1) {
        fprintf(stderr,
                "wl-screenhack: eglChooseConfig returned 0 matching configs on select\n");
        exit(1);
    }
    return cfg;
}

static void init_wayland(struct app *app) {
    app->display = wl_display_connect(NULL);
    if (!app->display) {
        fprintf(stderr,
                "wl-screenhack: wl_display_connect failed — is WAYLAND_DISPLAY set?\n");
        exit(1);
    }

    app->registry = wl_display_get_registry(app->display);
    if (!app->registry) {
        fprintf(stderr, "wl-screenhack: wl_display_get_registry returned NULL\n");
        exit(1);
    }

    /* The registry listener will fill compositor / seat / output / layer_shell. */
    wl_registry_add_listener(app->registry, &registry_listener, app);

    /* First roundtrip: deliver globals. */
    if (wl_display_roundtrip(app->display) < 0) {
        fprintf(stderr, "wl-screenhack: %s\n", "wl_display_roundtrip (registry bind) failed");
        exit(1);
    }

    if (!app->compositor) {
        fprintf(stderr, "wl-screenhack: wl_compositor not advertised by compositor\n");
        exit(1);
    }
    if (!app->layer_shell) {
        fprintf(stderr,
                "wl-screenhack: zwlr_layer_shell_v1 not advertised — "
                "is the compositor wlr-based?\n");
        exit(1);
    }
    if (!app->seat) {
        fprintf(stderr, "wl-screenhack: wl_seat not advertised\n");
        exit(1);
    }
    /* Seat listener must be added AFTER we have a seat — the capabilities
     * event fires when we roundtrip again below. */
    wl_seat_add_listener(app->seat, &seat_listener, app);

    /* Bind keyboard if it's already present. */
    if (wl_display_roundtrip(app->display) < 0) {
        fprintf(stderr, "wl-screenhack: %s\n", "wl_display_roundtrip (seat caps) failed");
        exit(1);
    }

    /* Set up the EGL *display / config / context* before creating the
     * layer surface. The actual window surface and makeCurrent happen
     * later — in the first configure callback — once we know the
     * compositor's negotiated width/height. */
    init_egl(app);

    /* Create the surface + layer surface. */
    app->surface = wl_compositor_create_surface(app->compositor);
    if (!app->surface) {
        fprintf(stderr, "wl-screenhack: wl_compositor_create_surface returned NULL\n");
        exit(1);
    }

    app->layer_surface = zwlr_layer_shell_v1_get_layer_surface(
        app->layer_shell, app->surface, app->output,
        ZWLR_LAYER_SHELL_V1_LAYER_OVERLAY, "wl-screenhack");
    if (!app->layer_surface) {
        fprintf(stderr, "wl-screenhack: zwlr_layer_shell_v1_get_layer_surface returned NULL\n");
        exit(1);
    }

    /* Anchor to all four edges — we want full-screen overlay. */
    zwlr_layer_surface_v1_set_anchor(app->layer_surface,
        ZWLR_LAYER_SURFACE_V1_ANCHOR_TOP
        | ZWLR_LAYER_SURFACE_V1_ANCHOR_BOTTOM
        | ZWLR_LAYER_SURFACE_V1_ANCHOR_LEFT
        | ZWLR_LAYER_SURFACE_V1_ANCHOR_RIGHT);

    /* exclusive_zone=-1 means: this surface is NOT used to reserve space
     * for other layers — it may overlap them. */
    zwlr_layer_surface_v1_set_exclusive_zone(app->layer_surface, -1);

    /* We want all key events so we can quit on any key press. EXCLUSIVE
     * means: this layer surface receives all keyboard input from the
     * compositor (focus is forced onto us, regardless of any other
     * surface that might want it). A screensaver wants exactly this —
     * any keypress should dismiss it.
     *
     * Note: v4 of wlr-layer-shell-unstable-v1 only defines NONE /
     * EXCLUSIVE / ON_DEMAND; there is no _ON. */

    zwlr_layer_surface_v1_set_keyboard_interactivity(
        app->layer_surface, ZWLR_LAYER_SURFACE_V1_KEYBOARD_INTERACTIVITY_EXCLUSIVE);

    zwlr_layer_surface_v1_add_listener(app->layer_surface,
                                       &layer_surface_listener, app);

    /* Per protocol: first commit must be with no buffer attached, after
     * which the compositor delivers a configure event. */
    wl_surface_commit(app->surface);

    /* Deliver the configure event. */
    if (wl_display_roundtrip(app->display) < 0) {
        fprintf(stderr, "wl-screenhack: %s\n", "wl_display_roundtrip (configure) failed");
        exit(1);
    }

    if (!app->configured) {
        fprintf(stderr,
                "wl-screenhack: layer_surface never configured after first commit\n");
        exit(1);
    }
}

/*
 * Initialize the EGL *display*, pick a config, and create a GLES2 context.
 *
 * Called from init_wayland() after the Wayland globals are bound but before
 * the layer surface is created. The EGL *window surface* and eglMakeCurrent
 * are NOT done here — those happen inside the layer_surface.configure
 * callback, once we know the compositor-negotiated width/height.
 */
static void init_egl(struct app *app) {
    /* eglGetPlatformDisplay is the modern, non-deprecated path; on EGL
     * 1.5 it is core; on EGL 1.4 it's available via EGL_EXT_platform_wayland.
     * Mesa advertises it on Wayland. */
    app->egl_display = eglGetPlatformDisplay(EGL_PLATFORM_WAYLAND_KHR,
                                             app->display, NULL);
    if (app->egl_display == EGL_NO_DISPLAY) {
        /* Fallback for very old EGL: try the legacy eglGetDisplay. */
        app->egl_display = eglGetDisplay((EGLNativeDisplayType)app->display);
        if (app->egl_display == EGL_NO_DISPLAY) {
            fprintf(stderr,
                    "wl-screenhack: eglGetPlatformDisplay(EGL_PLATFORM_WAYLAND_KHR) failed\n");
            exit(1);
        }
    }

    EGLint major = 0, minor = 0;
    if (!eglInitialize(app->egl_display, &major, &minor)) {
        fprintf(stderr, "wl-screenhack: eglInitialize failed (0x%x)\n",
                (unsigned int)eglGetError());
        exit(1);
    }

    /* EGL's current-bound client rendering API defaults to EGL_OPENGL_API
     * on implementations that also support desktop GL (Mesa does); without
     * an explicit bind here, eglCreateContext below can succeed while the
     * subsequent GLES2 calls (glCreateShader etc.) silently fail because no
     * ES context is actually current. Must bind before choosing the config
     * or creating the context. */
    if (!eglBindAPI(EGL_OPENGL_ES_API)) {
        fprintf(stderr, "wl-screenhack: eglBindAPI(EGL_OPENGL_ES_API) failed (0x%x)\n",
                (unsigned int)eglGetError());
        exit(1);
    }

    app->egl_config = choose_egl_config(app->egl_display);

    /* Bind GLES2 — we ask for an OpenGL ES 2.0 context. */
    EGLint ctx_attr[] = {
        EGL_CONTEXT_CLIENT_VERSION, 2,
        EGL_NONE,
    };
    app->egl_context =
        eglCreateContext(app->egl_display, app->egl_config,
                         EGL_NO_CONTEXT, ctx_attr);
    if (app->egl_context == EGL_NO_CONTEXT) {
        fprintf(stderr, "wl-screenhack: eglCreateContext (GLES2) failed (0x%x)\n",
                (unsigned int)eglGetError());
        exit(1);
    }
}

/* -------------------------------------------------------------------------- */
/* Clean shutdown                                                             */
/* -------------------------------------------------------------------------- */

static void app_fini(struct app *app) {
    /* Idempotent — safe to call from error paths. */

    if (app->frame_cb) {
        wl_callback_destroy(app->frame_cb);
        app->frame_cb = NULL;
    }

    if (app->effect && app->configured) {
        app->effect->free(app->effect);
    }

    if (app->egl_context != EGL_NO_CONTEXT) {
        eglMakeCurrent(app->egl_display, EGL_NO_SURFACE, EGL_NO_SURFACE,
                       EGL_NO_CONTEXT);
        eglDestroyContext(app->egl_display, app->egl_context);
        app->egl_context = EGL_NO_CONTEXT;
    }
    if (app->egl_surface != EGL_NO_SURFACE) {
        eglDestroySurface(app->egl_display, app->egl_surface);
        app->egl_surface = EGL_NO_SURFACE;
    }
    if (app->egl_window) {
        wl_egl_window_destroy(app->egl_window);
        app->egl_window = NULL;
    }
    if (app->egl_display != EGL_NO_DISPLAY) {
        eglTerminate(app->egl_display);
        app->egl_display = EGL_NO_DISPLAY;
    }

    if (app->keyboard)  { wl_keyboard_release(app->keyboard);  app->keyboard  = NULL; }
    if (app->layer_surface) {
        zwlr_layer_surface_v1_destroy(app->layer_surface);
        app->layer_surface = NULL;
    }
    if (app->surface)   { wl_surface_destroy(app->surface);   app->surface   = NULL; }
    if (app->layer_shell) { zwlr_layer_shell_v1_destroy(app->layer_shell); app->layer_shell = NULL; }
    if (app->seat)        { wl_seat_release(app->seat);             app->seat        = NULL; }
    if (app->output)      { wl_output_release(app->output);         app->output      = NULL; }
    if (app->compositor)  { wl_compositor_destroy(app->compositor); app->compositor  = NULL; }
    if (app->registry)    { wl_registry_destroy(app->registry);    app->registry    = NULL; }
    if (app->display)     { wl_display_disconnect(app->display);   app->display     = NULL; }
}

/* -------------------------------------------------------------------------- */
/* main                                                                       */
/* -------------------------------------------------------------------------- */

/* atexit-cleanup: app_fini is idempotent (everything it touches is
 * NULLed/NO_*_-checked), so it's safe to call from any exit path —
 * error paths via the DIE macro, signal-handler-caused exits, normal
 * returns from main. Registered before any resource acquisition. */
static void atexit_app_fini(void) {
    if (g_app_for_signal) {
        app_fini(g_app_for_signal);
        g_app_for_signal = NULL;
    }
}

int main(void) {
    /* static: atexit(atexit_app_fini) runs AFTER main() returns, when
     * this variable would otherwise be automatic (stack) storage with
     * expired lifetime -- g_app_for_signal pointed into a dead frame,
     * observed on real hardware as app->effect reading back as garbage
     * (0xaaaa00000001) inside app_fini, SIGSEGV. static gives it program
     * lifetime so the atexit handler sees valid data. */
    static struct app app;
    memset(&app, 0, sizeof app);
    app.egl_display = EGL_NO_DISPLAY;
    app.egl_surface = EGL_NO_SURFACE;
    app.egl_context = EGL_NO_CONTEXT;
    app.running     = 1;
    app.effect      = &g_test_triangle_effect;

    g_app_for_signal = &app;
    if (atexit(atexit_app_fini) != 0) {
        fprintf(stderr, "wl-screenhack: atexit registration failed\n");
        exit(1);
    }
    install_signals();

    init_wayland(&app);
    /* EGL display/config/context are initialized inside init_wayland,
     * before the layer surface is created; the window surface and
     * makeCurrent happen inside the first configure callback. */

    /* Prime the render loop: draw one frame and swap so the compositor
     * has a buffer to present; this causes the frame callback we just
     * requested to actually fire on the next compositor cycle. */
    glViewport(0, 0, app.width, app.height);
    app.effect->draw(app.effect, monotonic_seconds());
    if (!eglSwapBuffers(app.egl_display, app.egl_surface)) {
        fprintf(stderr,
                "wl-screenhack: initial eglSwapBuffers failed (0x%x)\n",
                (unsigned int)eglGetError());
        exit(1);
    }
    request_frame(&app);

    /* Main loop.
     *
     * We use the wl_display_prepare_read / poll / read_events /
     * dispatch_pending pattern so that SIGINT/SIGTERM wake the poll
     * immediately (instead of being swallowed by libwayland's internal
     * EINTR retry loop). Plain wl_display_dispatch would also work but
     * could keep us blocked for an arbitrary time after a signal.
     */
    while (app.running) {
        while (wl_display_prepare_read(app.display) != 0) {
            /* Events already queued: dispatch them first. */
            if (wl_display_dispatch_pending(app.display) < 0) {
                fprintf(stderr,
                        "wl-screenhack: wl_display_dispatch_pending error: %s\n",
                        errno ? strerror(errno) : "unknown");
                app.running = 0;
                break;
            }
        }
        if (!app.running) break;

        /* Block until the Wayland fd is readable or we're interrupted
         * by a signal. POLLIN fires on compositor events. */
        struct pollfd pfd = {
            .fd     = wl_display_get_fd(app.display),
            .events = POLLIN,
        };
        int n = poll(&pfd, 1, -1);
        if (n < 0) {
            if (errno == EINTR) {
                /* Signal — drop out of prepare_read and re-check running. */
                wl_display_cancel_read(app.display);
                continue;
            }
            fprintf(stderr,
                    "wl-screenhack: poll error: %s\n", strerror(errno));
            wl_display_cancel_read(app.display);
            app.running = 0;
            break;
        }
        if (n == 0) continue; /* shouldn't happen with -1 timeout, but be safe */

        /* Read events from the fd, then dispatch. */
        if (wl_display_read_events(app.display) < 0) {
            fprintf(stderr,
                    "wl-screenhack: wl_display_read_events error: %s\n",
                    errno ? strerror(errno) : "unknown");
            app.running = 0;
            break;
        }
        if (wl_display_dispatch_pending(app.display) < 0) {
            fprintf(stderr,
                    "wl-screenhack: wl_display_dispatch_pending error: %s\n",
                    errno ? strerror(errno) : "unknown");
            app.running = 0;
            break;
        }
    }

    /* Flush any pending outgoing requests before tearing down.
     * atexit_app_fini (registered below) will release all resources. */
    if (app.display) wl_display_roundtrip(app.display);

    return 0;
    /* atexit handler runs app_fini. */
}
