static struct app *g_app_for_signal = NULL;

static void on_signal(int sig) {
    (void)sig;
    if (g_app_for_signal) g_app_for_signal->running = 0;
    /* Re-raise? No — we want the main loop to observe `running == 0` and
     * quit cleanly. */
}

static void install_signals(void) {
    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_handler = on_signal;
    sigemptyset(&sa.sa_mask);
    /* Block the OTHER signal during handler so we don't reenter. */
    sigaddset(&sa.sa_mask, SIGINT);
    sigaddset(&sa.sa_mask, SIGTERM);
    DIE(sigaction(SIGINT,  &sa, NULL), 0, "sigaction(SIGINT) failed");
    DIE(sigaction(SIGTERM, &sa, NULL), 0, "sigaction(SIGTERM) failed");

    /* Ignore SIGPIPE — we don't write to sockets via fd write paths here,
     * but the compositor connection is a socket and EPIPE is harmless. */
    struct sigaction ign;
    memset(&ign, 0, sizeof ign);
    ign.sa_handler = SIG_IGN;
    sigemptyset(&ign.sa_mask);
    DIE(sigaction(SIGPIPE, &ign, NULL), 0, "sigaction(SIGPIPE) failed");
}

/* -------------------------------------------------------------------------- */
/* Monotonic clock                                                            */
/* -------------------------------------------------------------------------- */

static double monotonic_seconds(void) {
    struct timespec ts;
    /* CLOCK_MONOTONIC is the right choice: not affected by wall-clock
     * changes, always strictly increasing. */
    if (clock_gettime(CLOCK_MONOTONIC, &ts) != 0) {
        fprintf(stderr, "wl-screenhack: clock_gettime(CLOCK_MONOTONIC) failed\n");
        exit(1);
    }
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
}

