static void registry_handle_global(void *data,
                                   struct wl_registry *registry,
                                   uint32_t name,
                                   const char *interface,
                                   uint32_t version) {
    (void)version;
    struct app *app = data;

    if (strcmp(interface, wl_compositor_interface.name) == 0) {
        app->compositor =
            wl_registry_bind(registry, name, &wl_compositor_interface, 4);
    } else if (strcmp(interface, wl_seat_interface.name) == 0) {
        /* Request v7 — current wl_seat is at v11 but v7 is sufficient for
         * get_keyboard + capabilities, and avoids dragging in newer
         * event signatures we don't use. */
        app->seat = wl_registry_bind(registry, name, &wl_seat_interface, 7);
    } else if (strcmp(interface, wl_output_interface.name) == 0) {
        if (app->output == NULL) {
            /* Bind at least one output so the layer-shell has a target.
             * v4 is the current stable. */
            app->output =
                wl_registry_bind(registry, name, &wl_output_interface, 4);
        }
    } else if (strcmp(interface, zwlr_layer_shell_v1_interface.name) == 0) {
        /* v4 of wlr-layer-shell is sufficient for our feature set; v5
         * adds the on_demand keyboard interactivity we don't use. */
        app->layer_shell =
            wl_registry_bind(registry, name,
                             &zwlr_layer_shell_v1_interface, 4);
    } else if (strcmp(interface, xdg_wm_base_interface.name) == 0) {
        /* xdg-shell is bound here to prove the protocol XML is being
         * compiled into the binary; we don't keep the pointer because
         * the layer-shell gives us everything we need. Future rounds
         * (e.g. a file-chooser dialog) may stash this in app->xdg_wm. */
        struct xdg_wm_base *xdg = wl_registry_bind(registry, name,
                                                  &xdg_wm_base_interface, 1);
        if (xdg) xdg_wm_base_destroy(xdg);
    }
}

