#!/usr/bin/env python3
"""Generate docs/HOST-TEST-RESULTS.md from host-test.sh result directories.

usage: gen-host-results-md.py RESULTS_DIR [RESULTS_DIR ...] -o docs/HOST-TEST-RESULTS.md
       [--evidence-dir docs/host-test-evidence]

Each RESULTS_DIR is either a single host directory (contains results.json) or
a stamp directory with one subdirectory per host.  With --evidence-dir, the
screenshots (converted to small JPEGs when ImageMagick is available) and logs
are copied next to the document and linked from it.  Output is deterministic
apart from the generation stamp, which comes from the newest results file.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HOST_ORDER = ["chimera", "medusa", "pegasus", "pegasus-nvidia", "o6n"]
PHASES = [
    "env",
    "install",
    "launcher",
    "idle",
    "multioutput",
    "session",
    "color",
    "chooser",
]


def find_hosts(dirs):
    hosts = {}
    for d in dirs:
        d = Path(d)
        if (d / "results.json").is_file():
            hosts[d.name] = d
            continue
        for sub in sorted(d.iterdir()) if d.is_dir() else []:
            if (sub / "results.json").is_file():
                hosts[sub.name] = sub
    return dict(
        sorted(
            hosts.items(),
            key=lambda kv: (
                HOST_ORDER.index(kv[0]) if kv[0] in HOST_ORDER else 99,
                kv[0],
            ),
        )
    )


def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def copy_evidence(src_dir, dest_dir, rel):
    """Copy shots/logs; returns mapping of original relative path -> doc path."""
    mapping = {}
    conv = shutil.which("magick") or shutil.which("convert")
    for sub in ("shots", "logs"):
        s = src_dir / sub
        if not s.is_dir():
            continue
        out = dest_dir / sub
        out.mkdir(parents=True, exist_ok=True)
        for f in sorted(s.iterdir()):
            if f.suffix == ".ppm":
                continue  # raw analysis frames are not evidence
            if sub == "shots" and f.suffix == ".png" and conv:
                target = out / (f.stem + ".jpg")
                cmd = [conv, str(f), "-resize", "480x", "-quality", "60", str(target)]
                subprocess.run(cmd, check=False, capture_output=True)
                if not target.exists():
                    shutil.copy(f, out / f.name)
                    target = out / f.name
            else:
                target = out / f.name
                shutil.copy(f, target)
            mapping[f"{sub}/{f.name}"] = f"{rel}/{sub}/{target.name}"
    return mapping


def pct(v):
    return "-" if v is None else f"{100 * v:.0f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--evidence-dir")
    ap.add_argument("--notes", help="Markdown file inserted after the summary table")
    args = ap.parse_args()
    hosts = find_hosts(args.dirs)
    if not hosts:
        sys.exit("no results.json found")
    out_path = Path(args.output)
    data = {h: json.loads((d / "results.json").read_text()) for h, d in hosts.items()}
    evid = {}
    if args.evidence_dir:
        ev_root = Path(args.evidence_dir)
        rel_root = os.path.relpath(ev_root, out_path.parent)
        for h, d in hosts.items():
            evid[h] = copy_evidence(d, ev_root / h, f"{rel_root}/{h}")

    L = []
    L.append("# Host test results")
    L.append("")
    L.append(
        "Generated by `tools/gen-host-results-md.py` from `tools/host-test.sh` runs. American English, deterministic layout."
    )
    L.append("")
    L.append(
        "Gate for every hack: at least 15% of the frame lit (any channel above 16), frame-to-frame motion of at least 0.5% of pixels, "
        "process alive at capture time and gone after `ncz-screensaver stop`. The difference from the desktop baseline is recorded but informational."
    )
    L.append("")
    L.append("## Summary")
    L.append("")
    L.append("| Host | Arch | Kernel | GPU / renderer | Package | Pass | Fail | Skip |")
    L.append("|---|---|---|---|---|---|---|---|")
    for h, d in data.items():
        s = d.get("summary", {})
        egl = (d.get("gpu") or {}).get("egl") or {}
        gpu = egl.get("gles_renderer") or (d.get("gpu") or {}).get("driver", "?")
        if d.get("gpu_offload") == "prime":
            hk = [x for x in d.get("hacks", []) if x.get("metrics", {}).get("renderer")]
            if hk:
                gpu = "offload to " + hk[0]["metrics"]["renderer"]
        pkg = (d.get("package") or {}).get("ncz-screensavers", "-")
        L.append(
            f"| {h} | {d.get('arch', '?')} | {esc(d.get('kernel', '?'))} | {esc(gpu)} | {pkg} | {s.get('pass', 0)} | {s.get('fail', 0)} | {s.get('skip', 0)} |"
        )
    L.append("")

    if args.notes:
        L.append(Path(args.notes).read_text().rstrip())
        L.append("")

    # Matrix of hacks x hosts.
    ids = {}
    for d in data.values():
        for hk in d.get("hacks", []):
            ids.setdefault(hk["id"], hk.get("group", ""))
    if ids:
        L.append(
            "## Hack matrix (pixel coverage; sparse = passes only through the tile rule)"
        )
        L.append("")
        L.append("| Hack | Group | " + " | ".join(data) + " |")
        L.append("|---|---|" + "---|" * len(data))
        for hid, grp in sorted(ids.items(), key=lambda kv: (kv[1], kv[0])):
            cells = []
            for h, d in data.items():
                row = next((x for x in d.get("hacks", []) if x["id"] == hid), None)
                if row is None:
                    cells.append("n/a")
                elif row["status"] == "pass" and row["metrics"].get("sparse"):
                    cells.append(
                        f"PASS sparse (tiles {pct(row['metrics'].get('tile_coverage'))})"
                    )
                elif row["status"] == "pass":
                    cells.append(f"PASS {pct(row['metrics'].get('coverage'))}")
                else:
                    cells.append("**FAIL**")
            L.append(f"| `{hid}` | {esc(grp)} | " + " | ".join(cells) + " |")
        L.append("")

    for h, d in data.items():
        L.append(f"## {h}")
        L.append("")
        gpu = d.get("gpu") or {}
        L.append(
            f"- Host name: `{d.get('host', '?')}`; arch {d.get('arch', '?')}; kernel `{d.get('kernel', '?')}`"
        )
        L.append(f"- Display devices: {esc(gpu.get('lspci', '?'))[:400]}")
        L.append(f"- Kernel driver(s): {esc(gpu.get('driver', '?'))}")
        egl = gpu.get("egl") or {}
        L.append(
            f"- GLES renderer: {esc(egl.get('gles_renderer', '?'))}; {esc(egl.get('gles_version', '?'))}"
        )
        L.append(f"- Packages: {esc(json.dumps(d.get('package', {}), sort_keys=True))}")
        L.append(f"- Compositor: {esc(json.dumps(d.get('compositor', {})))}")
        L.append(
            f"- Started {d.get('started', '?')}, finished {d.get('finished', '?')}"
        )
        L.append("")
        phases = d.get("phases", {})
        for ph in PHASES:
            checks = phases.get(ph) or []
            if not checks:
                continue
            L.append(f"### {h}: {ph}")
            L.append("")
            L.append("| Check | Status | Detail |")
            L.append("|---|---|---|")
            for c in checks:
                ev = c.get("evidence")
                link = ""
                if ev and ev in evid.get(h, {}):
                    link = f" [evidence]({evid[h][ev]})"
                L.append(
                    f"| {esc(c['name'])} | {c['status'].upper()} | {esc(c.get('detail', ''))[:300]}{link} |"
                )
            L.append("")
        hacks = d.get("hacks", [])
        if hacks:
            L.append(f"### {h}: hacks")
            L.append("")
            L.append(
                "| Hack | Group | Result | Pixel coverage | Tile coverage | Motion | Stop (s) | Evidence |"
            )
            L.append("|---|---|---|---|---|---|---|---|")
            for hk in sorted(hacks, key=lambda x: (x.get("group", ""), x["id"])):
                m = hk.get("metrics", {})
                ev = hk.get("evidence")
                key = f"shots/{ev}" if ev else None
                if (
                    key
                    and key not in evid.get(h, {})
                    and ev
                    and key.replace(".png", ".jpg") in evid.get(h, {})
                ):
                    key = key.replace(".png", ".jpg")
                link = (
                    f"[shot]({evid[h][key]})"
                    if key and key in evid.get(h, {})
                    else (esc(ev) if ev else "")
                )
                result = hk["status"].upper() + (" (sparse)" if m.get("sparse") else "")
                L.append(
                    f"| `{hk['id']}` | {esc(hk.get('group', ''))} | {result} | {pct(m.get('coverage'))} | "
                    f"{pct(m.get('tile_coverage'))} | {pct(m.get('motion'))} | {m.get('stop_seconds', '-')} | {link} |"
                )
            failed = [hk for hk in hacks if hk["status"] != "pass"]
            if failed:
                L.append("")
                L.append(f"Failures on {h}:")
                L.append("")
                for hk in failed:
                    L.append(f"- `{hk['id']}`: {esc(hk.get('detail', ''))[:300]}")
            L.append("")
    out_path.write_text("\n".join(L) + "\n")
    print(f"wrote {out_path} ({len(hosts)} hosts)")


if __name__ == "__main__":
    main()
