/*
 * ncz-screensaver-idled - NCZ-OS screensaver idle timer daemon.
 *
 * Subscribes to ext-idle-notify-v1 on the Wayland session seat and fires three
 * notifications derived from the dev.ncz.screensaver GSettings schema:
 *
 *   - saver:   hack-idle-delay seconds   -> "ncz-screensaver start --idle"
 *              resumed                   -> "ncz-screensaver stop"
 *   - lock:    saver + lock-delay        -> stop the screensaver, then run
 *                                          the lock command (never twice
 *                                          concurrently)
 *   - dpms:    display-off-delay seconds -> zwlr-output-power off / on
 *
 * Plan rules (pure function, see plan_compute() below):
 *   - saver is disabled when mode == "off" (no animated hack).
 *   - lock is disabled when lock-enabled is false. When mode == "off" the lock
 *     happens at hack-idle-delay; otherwise it follows lock-delay after saver.
 *   - dpms is disabled when display-off-delay == 0.
 *
 * The daemon also listens for logind's PrepareForSleep and session Lock
 * signals, optionally holding a "delay" sleep inhibitor to keep the sleep
 * transition long enough for the lock command to spawn before it returns.
 *
 * All work happens on a single GLib main loop with a custom GSource that drives
 * the Wayland display; the daemon exits non-zero on disconnect so systemd can
 * restart it.
 *
 * Build deps (see launcher/meson.build): glib-2.0, gio-2.0, gio-unix-2.0,
 * wayland-client. The two ext-idle-notify-v1 and wlr-output-power-management
 * headers are generated from protocols XML files by wayland-scanner.
 */

