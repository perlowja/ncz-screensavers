static gboolean on_signal_term(gpointer user_data)
{
    struct idled_state *st = user_data;
    log_info("SIGTERM/INT received, shutting down");
    request_shutdown(st, 0);
    return G_SOURCE_REMOVE;
}

static gboolean on_signal_hup(gpointer user_data)
{
    struct idled_state *st = user_data;
    log_info("SIGHUP received, reloading settings");
    settings_load(st->gsettings, &st->cur_settings);
    plan_apply(st, &st->cur_settings);
    return G_SOURCE_CONTINUE;
}

static gboolean on_settings_changed_debounced(gpointer user_data)
{
    struct idled_state *st = user_data;
    st->settings_debounce = 0;
    settings_load(st->gsettings, &st->cur_settings);
    plan_apply(st, &st->cur_settings);
    return G_SOURCE_REMOVE;
}

static void on_settings_changed(GSettings *settings, const char *key, gpointer user_data)
{
    (void)settings; (void)key;
    struct idled_state *st = user_data;
    /* Debounce 300 ms: the chooser plugin can fire several keys together. */
    if (st->settings_debounce) g_source_remove(st->settings_debounce);
    st->settings_debounce = g_timeout_add(300, on_settings_changed_debounced, st);
}

static GMainLoop *g_loop;

static void request_shutdown(struct idled_state *st, int code)
{
    if (st->_shutdown) return;
    st->_shutdown = TRUE;
    st->_exit_code = code;
    if (g_loop) g_main_loop_quit(g_loop);
}

/* ------------------------------------------------------------------------- *
 * Top-level teardown / state init
 * ------------------------------------------------------------------------- */

static void state_init(struct idled_state *st)
{
    memset(st, 0, sizeof *st);
    st->logind_inhibit_fd_raw = -1;
    st->saver_pid = st->stop_pid = st->lock_pid = -1;
    st->state_file_path = state_file_path_alloc();
    st->_state_label = g_strdup("active");
}

static void state_teardown(struct idled_state *st)
{
    /* Restore outputs to ON, then destroy per-output power objects. */
    if (st->w_powers && st->w_powers->len > 0) {
        struct output_power *arr = (struct output_power *)st->w_powers->data;
        for (guint i = 0; i < st->w_powers->len; i++) {
            if (arr[i].power) {
                zwlr_output_power_v1_set_mode(arr[i].power,
                    ZWLR_OUTPUT_POWER_V1_MODE_ON);
                zwlr_output_power_v1_destroy(arr[i].power);
            }
        }
    }
    if (st->w_idle) {
        if (st->w_saver_notif) ext_idle_notification_v1_destroy(st->w_saver_notif);
        if (st->w_lock_notif)  ext_idle_notification_v1_destroy(st->w_lock_notif);
        if (st->w_dpms_notif)  ext_idle_notification_v1_destroy(st->w_dpms_notif);
        st->w_saver_notif = st->w_lock_notif = st->w_dpms_notif = NULL;
        ext_idle_notifier_v1_destroy(st->w_idle);
        st->w_idle = NULL;
    }
    if (st->w_pwr_mgr) {
        zwlr_output_power_manager_v1_destroy(st->w_pwr_mgr);
        st->w_pwr_mgr = NULL;
    }
    if (st->w_powers) { g_array_free(st->w_powers, TRUE); st->w_powers = NULL; }
    if (st->w_outputs) { g_array_free(st->w_outputs, TRUE); st->w_outputs = NULL; }
    if (st->w_seat)    { wl_seat_destroy(st->w_seat); st->w_seat = NULL; }
    if (st->w_registry){ wl_registry_destroy(st->w_registry); st->w_registry = NULL; }
    if (st->w_display) { wl_display_disconnect(st->w_display); st->w_display = NULL; }
    if (st->logind_inhibit_fd_raw >= 0) close(st->logind_inhibit_fd_raw);
    if (st->logind_cancellable)        g_object_unref(st->logind_cancellable);
    if (st->logind_conn)               g_object_unref(st->logind_conn);
    g_free(st->logind_session_path);
    state_file_remove(st);
    g_free(st->state_file_path);
    g_free(st->_state_label);
    settings_clear(&st->cur_settings);
    if (st->gsettings) g_object_unref(st->gsettings);
    if (st->settings_debounce) g_source_remove(st->settings_debounce);
}

